const fmt = (n) => Math.round(n).toLocaleString('en');
let printed = 0;
while (!sim.finished) {
  for (const item of sim.inbox()) {
    if (item.deliverable) {
      if (DOCS[item.eventId]) {
        const ev = sim.submitDeliverable(item.id, DOCS[item.eventId]);
        if (!quiet) console.log(`  📄 يوم ${sim.day}: سلّمت «${item.title}» — الدرجة ${Math.round(ev.score * 100)}%`);
      }
    } else if (CHOICES[item.eventId]) {
      const [opt, why] = CHOICES[item.eventId];
      const o = sim.respond(item.id, opt, { rationale: why });
      if (!quiet) console.log(`  ✅ يوم ${sim.day}: «${item.title}» ← ${o.label}`);
    }
  }
  sim.endDay();
  if (!quiet) for (; printed < sim.feed.length; printed++) {
    const f = sim.feed[printed];
    console.log(`     ${f.tone === 'bad' ? '🔻' : f.tone === 'good' ? '🔺' : '•'} ${f.text}`);
  }
}

