// فحص مهام البحث وساعات اليوم في المتصفح.
import { createRequire } from 'node:module';
import { goodRun } from '../lib/runs.js';
const { chromium } = createRequire(import.meta.url)('playwright');
const O = 'http://localhost:4173';
const SH = process.env.SHOTS || '/tmp';
let cookie = '';
const call = async (m, p, b) => { const r = await fetch(O + p, { method: m, headers: { 'Content-Type': 'application/json', ...(cookie ? { cookie } : {}) }, body: b ? JSON.stringify(b) : undefined }); const s = r.headers.get('set-cookie'); if (s) cookie = s.split(';')[0]; return r.json().catch(() => ({})); };
await call('POST', '/api/auth/register', { name: 'ريم', email: `rs-${Date.now()}@x.sa`, password: 'secret-123', consents: { processing: true } });
await call('PUT', '/api/progress', goodRun(6, { stopDay: 8 }));
const errs = [];
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } });
await ctx.addCookies([{ name: 'mohaki_session', value: cookie.split('=')[1], url: O }]);
const p = await ctx.newPage(); p.on('pageerror', (e) => errs.push(e.message));
await p.goto(`${O}/app/#/inbox`);
await p.locator('.inbox-list .item', { hasText: 'لماذا خسرنا' }).click();
await p.waitForSelector('.src-grid');
if (!(await p.locator('.hours b').textContent()).includes('8')) errs.push('hours not 8 at day start');
await p.locator('.src', { hasText: 'ماجد' }).click();
await p.locator('.src', { hasText: 'سجل الصفقات' }).click();
await p.locator('.src', { hasText: 'فهد' }).click();
await p.waitForSelector('.pending');
await p.screenshot({ path: `${SH}/rs-research.png`, fullPage: true });
for (let i = 0; i < 3; i++) await p.click('[data-act="work-hour"]');
if (await p.locator('.pending').count()) errs.push('analysis not ready after 3 hours');
if (!(await p.locator('.finding').last().textContent()).includes('26 ساعة')) errs.push('analysis finding missing');
await p.locator('.research-form .seg label', { hasText: 'تأخر الرد' }).click();
await p.fill('.research-form input[name="count"]', '4');
await p.getByRole('button', { name: 'سلّم الجواب' }).click();
await p.waitForSelector('.outcome.good');
const left = await p.locator('.hours b').textContent();
if (left.trim() !== '3.25') errs.push(`hours left: ${left}`);
await p.screenshot({ path: `${SH}/rs-done.png` });
await b.close();
console.log(errs.length ? errs.join('\n') : 'ok');
