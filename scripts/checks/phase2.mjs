import { createRequire } from 'node:module';
import { goodRun } from '../lib/runs.js';
const { chromium } = createRequire(import.meta.url)('playwright');
const O = 'http://localhost:4173';
const SH = process.env.SHOTS || '/tmp';
let cookie = '';
const call = async (m, p, b) => { const r = await fetch(O + p, { method: m, headers: { 'Content-Type': 'application/json', ...(cookie ? { cookie } : {}) }, body: b ? JSON.stringify(b) : undefined }); const s = r.headers.get('set-cookie'); if (s) cookie = s.split(';')[0]; return r.json().catch(() => ({})); };
await call('POST', '/api/auth/register', { name: 'ريم', email: `p2-${Date.now()}@x.sa`, password: 'secret-123', consents: { processing: true } });
// اليوم 6 بعد أن أنهى كل بنوده
const run = goodRun(9, { stopDay: 5 });
await call('PUT', '/api/progress', run);
const errs = [];
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } });
await ctx.addCookies([{ name: 'mohaki_session', value: cookie.split('=')[1], url: O }]);
const p = await ctx.newPage();
p.on('pageerror', (e) => errs.push(e.message));
await p.goto(`${O}/app/#/inbox?f=all`);
await p.waitForSelector('.inbox-list');
const titles = await p.locator('.inbox-list .item .tt').allTextContents();
console.log(titles.slice(0, 8).join(' | '));
await p.locator('.inbox-list .item', { hasText: 'التقرير الصباحي — يوم العمل 6' }).click();
await p.waitForSelector('.report-tbl');
await p.screenshot({ path: `${SH}/p2-report.png`, fullPage: true });
await p.locator('.inbox-list .item', { hasText: 'اجتماع الموظفين' }).first().click();
await p.waitForSelector('.memo');
await p.goto(`${O}/app/#/desk`);
await p.waitForSelector('.hero');
const hasWhat = await p.locator('.what-now').count();
console.log('what-now:', hasWhat, 'open:', await p.locator('.hero .stats b').first().textContent());
await p.screenshot({ path: `${SH}/p2-desk.png`, fullPage: true });
await b.close();
console.log(errs.length ? errs.join('\n') : 'ok');
