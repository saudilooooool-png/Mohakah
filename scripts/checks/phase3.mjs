import { createRequire } from 'node:module';
import { goodRun } from '../lib/runs.js';
const { chromium } = createRequire(import.meta.url)('playwright');
const O = 'http://localhost:4173';
const SH = process.env.SHOTS || '/tmp';
let cookie = '';
const call = async (m, p, b) => { const r = await fetch(O + p, { method: m, headers: { 'Content-Type': 'application/json', ...(cookie ? { cookie } : {}) }, body: b ? JSON.stringify(b) : undefined }); const s = r.headers.get('set-cookie'); if (s) cookie = s.split(';')[0]; return r.json().catch(() => ({})); };
await call('POST', '/api/auth/register', { name: 'ريم', email: `p3-${Date.now()}@x.sa`, password: 'secret-123', consents: { processing: true } });
await call('PUT', '/api/progress', goodRun(2, { stopDay: 7 }));
const errs = [];
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } });
await ctx.addCookies([{ name: 'mohaki_session', value: cookie.split('=')[1], url: O }]);
const p = await ctx.newPage();
p.on('pageerror', (e) => errs.push(e.message));
await p.goto(`${O}/app/#/desk`);
await p.waitForSelector('#office .ppl');
console.log('people:', await p.locator('#office .ppl').count());
await p.locator('#office').screenshot({ path: `${SH}/p3-office.png` });
// التكليف
await p.goto(`${O}/app/#/inbox`);
await p.locator('.inbox-list .item', { hasText: 'مقابلات المستخدمين' }).click();
await p.locator('.delegate summary').click();
await p.fill('#brief', 'يا ريان، رتّب مع ريم 5 مقابلات مع عملاء ألغوا اشتراكهم، والهدف معرفة سبب الإلغاء، وأرسل لي ملخصًا قبل الخميس.');
await p.screenshot({ path: `${SH}/p3-delegate.png` });
await p.getByRole('button', { name: 'إرسال التكليف' }).click();
await p.waitForSelector('.outcome.info');
await p.waitForTimeout(1200);
await p.screenshot({ path: `${SH}/p3-delegated.png` });
const cap = await p.locator('#office-mini .office-cap').textContent();
console.log('caption:', cap);
await p.locator('#office-mini').click({ position: { x: 5, y: 5 } }).catch(() => {});
// انتقال بالضغط على زميل
await p.goto(`${O}/app/#/desk`);
await p.waitForSelector('#office .ppl[data-id="analyst"]');
await p.locator('#office .ppl[data-id="analyst"]').click();
await p.waitForTimeout(400);
console.log('hash after click:', await p.evaluate(() => location.hash));
await b.close();
console.log(errs.length ? errs.join('\n') : 'ok');
