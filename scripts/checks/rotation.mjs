// فحص شهر دور آخر بالتدوير بين الإدارات، وبناء العلاقات، في المتصفح.
import { createRequire } from 'node:module';
import { goodRun } from '../lib/runs.js';
const { chromium } = createRequire(import.meta.url)('playwright');
const O = 'http://localhost:4173';
const SH = process.env.SHOTS || '/tmp';
let cookie = '';
const call = async (m, p, b) => { const r = await fetch(O + p, { method: m, headers: { 'Content-Type': 'application/json', ...(cookie ? { cookie } : {}) }, body: b ? JSON.stringify(b) : undefined }); const s = r.headers.get('set-cookie'); if (s) cookie = s.split(';')[0]; return r.json().catch(() => ({})); };
await call('POST', '/api/auth/register', { name: 'سارة العتيبي', email: `rot-${Date.now()}@x.sa`, password: 'secret-123', consents: { processing: true } });
await call('PUT', '/api/progress', goodRun(4, { stopDay: 10, scenario: 'sales-month' }));
const errs = [];
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } });
await ctx.addCookies([{ name: 'mohaki_session', value: cookie.split('=')[1], url: O }]);
const p = await ctx.newPage(); p.on('pageerror', (e) => errs.push(e.message));
await p.goto(`${O}/app/#/desk`);
await p.waitForSelector('.rot-chip');
if (!(await p.locator('.rot-chip').textContent()).includes('تدوير: نجاح العملاء')) errs.push(`chip: ${await p.locator('.rot-chip').textContent()}`);
if (!(await p.locator('.side-foot').textContent()).includes('Sales')) errs.push('role not sales');
await p.screenshot({ path: `${SH}/rot-desk.png`, fullPage: true });
await p.goto(`${O}/app/#/inbox`);
await p.waitForSelector('.inbox-list .item');
if (!(await p.locator('.inbox-list').textContent()).includes('تدويرك هذا الأسبوع في نجاح العملاء')) errs.push('rotation note missing');
await p.goto(`${O}/app/#/team`);
await p.waitForSelector('.network');
const card = p.locator('.card.person', { hasText: 'أمل الغامدي' });
await card.locator('[data-act="connect"]').click();
await p.waitForFunction(() => document.querySelector('.network .pf-stats b')?.textContent.trim() === '1');
if (!(await p.locator('.card.person', { hasText: 'أمل الغامدي' }).textContent()).includes('التقيتما 1')) errs.push('connect not recorded');
await p.locator('.card.person', { hasText: 'منصور القرشي' }).locator('[data-act="connect"]').click();
await p.waitForTimeout(400);
if ((await p.locator('.hours b').textContent()).trim() !== '7') errs.push(`hours after 2 sessions: ${await p.locator('.hours b').textContent()}`);
await p.screenshot({ path: `${SH}/rot-team.png` });
await p.reload(); await p.waitForSelector('.network');
if ((await p.locator('.network .pf-stats b').first().textContent()).trim() !== '1') errs.push('network lost after reload');
await b.close();
console.log(errs.length ? errs.join('\n') : 'ok');
