// فحص "خطتي" في المتصفح: سؤال الهدف، والخطوة التالية، ومؤشر الجاهزية.
import { createRequire } from 'node:module';
import { goodRun } from '../lib/runs.js';
const { chromium } = createRequire(import.meta.url)('playwright');
const O = 'http://localhost:4173';
const SH = process.env.SHOTS || '/tmp';
let cookie = '';
const call = async (m, p, b) => { const r = await fetch(O + p, { method: m, headers: { 'Content-Type': 'application/json', ...(cookie ? { cookie } : {}) }, body: b ? JSON.stringify(b) : undefined }); const s = r.headers.get('set-cookie'); if (s) cookie = s.split(';')[0]; return r.json().catch(() => ({})); };
await call('POST', '/api/auth/register', { name: 'ريم القحطاني', email: `pl-${Date.now()}@x.sa`, password: 'secret-123', consents: { processing: true } });
await call('PUT', '/api/progress', goodRun(6, { stopDay: 6 }));
const errs = [];
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } });
await ctx.addCookies([{ name: 'mohaki_session', value: cookie.split('=')[1], url: O }]);
const p = await ctx.newPage(); p.on('pageerror', (e) => errs.push(e.message));
await p.goto(`${O}/app/#/desk`);
await p.waitForSelector('.plan-strip');
await p.click('.plan-strip');
await p.waitForSelector('.plan-next');
if (!(await p.locator('.plan-next h2').textContent()).includes('حدّد هدفك')) errs.push('next step should be the goal');
await p.click('[data-act="edit-goal"]');
await p.locator('.modal label.opt', { hasText: 'مبيعات' }).click();
await p.locator('.modal label.opt', { hasText: 'خبرة عملية' }).click();
await p.screenshot({ path: `${SH}/pl-goal.png` });
await p.getByRole('button', { name: 'ابنِ خطتي' }).click();
await p.waitForFunction(() => !document.querySelector('.modal'));
const next = await p.locator('.plan-next h2').textContent();
if (!next.includes('أكّد بريدك')) errs.push(`next step after goal: ${next}`);
const n = Number(await p.locator('.plan-ring.big b').textContent());
if (!(n > 5 && n < 40)) errs.push(`readiness at day 7: ${n}`);
if (!(await p.content()).includes('مبيعات وتطوير أعمال')) errs.push('goal not shown');
await p.screenshot({ path: `${SH}/pl-plan.png`, fullPage: true });
await p.reload(); await p.waitForSelector('.plan-next');
if (!(await p.content()).includes('مبيعات وتطوير أعمال')) errs.push('goal lost after reload');
await b.close();
console.log(errs.length ? errs.join('\n') : 'ok');
